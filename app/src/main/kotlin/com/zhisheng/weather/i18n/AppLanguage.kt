val LocalAppLanguage = staticCompositionLocalOf { AppLanguage.CHINESE }

/** Also serves RemoteViews, Toast and accessibility text outside Compose. */
object AppLanguageState {
    @Volatile
    var current: AppLanguage = AppLanguage.CHINESE
}

@Composable
fun ProvideAppLanguage(language: AppLanguage, content: @Composable () -> Unit) {
    SideEffect { AppLanguageState.current = language }
    CompositionLocalProvider(LocalAppLanguage provides language, content = content)
}

fun uiText(text: String, language: AppLanguage = AppLanguageState.current): String {
    if (language != AppLanguage.JAPANESE || text.isBlank()) return text
    japaneseExact[text]?.let { return it }
    japaneseWeatherCopy(text)?.let { return it }

    var localized = text
    dynamicJapaneseRules.forEach { (pattern, replacement) ->
        localized = pattern.replace(localized, replacement)
    }
    japanesePhrases.forEach { (source, target) ->
        localized = localized.replace(source, target)
    }
    return localized
}

